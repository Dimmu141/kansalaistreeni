"""Check the bundled demo against its dated source-review ledger, using only stdlib.

This detects changed/unreviewed content; it cannot establish factual truth or human approval.
"""
import argparse
import hashlib
import json
import sys
from datetime import date
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8-sig"), object_pairs_hook=unique_object)


CLASSIFICATION = ("topicId", "objectiveIds")


def fingerprint(question):
    # Includes translation wording. Structural validation is also run by JVM tests. Classification
    # is excluded: moving a question to another topic or objective does not change the reviewed facts.
    reviewed = {key: value for key, value in question.items() if key not in CLASSIFICATION}
    text = json.dumps(reviewed, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


MIN_OBJECTIVE_QUESTIONS = 3
COVERAGE_REPORT = ROOT / "docs/CONTENT-COVERAGE.md"


def verify_objectives(content):
    """Structural objective checks; the app's importer applies the same rules."""
    objectives = content.get("objectives", [])
    topics = {t["id"] for t in content["topics"]}
    ids = [o["id"] for o in objectives]
    if len(set(ids)) != len(ids):
        raise ValueError("Duplicate objective ID")
    for objective in objectives:
        statement = objective["statement"]
        if objective["topicId"] not in topics or not statement.get("fi") or not statement.get("sv"):
            raise ValueError(f"Invalid objective: {objective['id']}")
    for q in content["questions"]:
        refs = q.get("objectiveIds", [])
        if objectives and (not refs or any(ref not in ids for ref in refs) or len(set(refs)) != len(refs)):
            raise ValueError(f"Question needs existing objectives: {q['id']}")


def coverage(content):
    """Rows of (topic, objective, {language: question count}) for languages taught in the package."""
    languages = sorted({q["language"] for q in content["questions"]})
    rows = []
    for topic in sorted(content["topics"], key=lambda t: t["order"]):
        for objective in (o for o in content.get("objectives", []) if o["topicId"] == topic["id"]):
            counts = {lang: sum(1 for q in content["questions"] if q["language"] == lang and objective["id"] in q.get("objectiveIds", [])) for lang in languages}
            rows.append((topic, objective, counts))
    return rows


def coverage_markdown(content):
    rows = coverage(content)
    languages = sorted({q["language"] for q in content["questions"]})
    thin = [r for r in rows if any(c < MIN_OBJECTIVE_QUESTIONS for c in r[2].values())]
    lines = [
        "# Content coverage",
        "",
        "Generated by `python scripts/verify-content.py --write-coverage` from the learning objectives in",
        f"`app/src/main/assets/demo-content.json` (package `{content['packageId']}` v{content['version']}). Do not edit by hand;",
        "the content gate fails when this file no longer matches the package.",
        "",
        "Objectives are this app's provisional mapping layer, not the official syllabus or exam format. Counts show how many",
        f"questions practise each objective per study language. Objectives with fewer than {MIN_OBJECTIVE_QUESTIONS} questions in a language are marked **thin**.",
        "",
        f"- Objectives: {len(rows)}",
        f"- Thin objectives: {len(thin)}",
        "- Questions: " + ", ".join(f"{lang.upper()} {sum(1 for q in content['questions'] if q['language'] == lang)}" for lang in languages),
        "",
    ]
    for topic in sorted(content["topics"], key=lambda t: t["order"]):
        topic_rows = [r for r in rows if r[0]["id"] == topic["id"]]
        if not topic_rows:
            continue
        lines += [f"## {topic['title']}", "", "| Objective | Statement | " + " | ".join(l.upper() for l in languages) + " | Note |",
                  "|---|---|" + "---|" * len(languages) + "---|"]
        for _, objective, counts in topic_rows:
            note = "thin" if any(c < MIN_OBJECTIVE_QUESTIONS for c in counts.values()) else ""
            ref = f" ({objective['sourceRef']})" if objective.get("sourceRef") else ""
            lines.append(f"| `{objective['id']}` | {objective['statement']['fi']}{ref} | " + " | ".join(str(counts[l]) for l in languages) + f" | {note} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def verify(content, ledger):
    if content["status"] != "DEMO" or any(q["status"] != "DEMO" for q in content["questions"]):
        raise ValueError("The bundled dataset must remain explicitly DEMO")
    if ledger["packageId"] != content["packageId"] or ledger["version"] != content["version"]:
        raise ValueError("Review ledger does not match the content package")
    questions = {q["id"]: q for q in content["questions"]}
    reviews = {r["questionId"]: r for r in ledger["reviews"]}
    if len(questions) != len(content["questions"]) or len(reviews) != len(ledger["reviews"]) or questions.keys() != reviews.keys():
        raise ValueError("Every question needs exactly one review record")
    for question_id, q in questions.items():
        review = reviews[question_id]
        if review["sha256"] != fingerprint(q):
            raise ValueError(f"Content changed after source review: {question_id}")
        if review["sourceUrl"] != q["source"]["url"] or not review["claim"] or not review["locator"]:
            raise ValueError(f"Incomplete source review: {question_id}")
        if date.fromisoformat(review["checkedAt"]) > date.today():
            raise ValueError(f"Future review date: {question_id}")
        if review["publicationApproved"] or review["reviewType"] != "ASSISTANT_SOURCE_CHECK":
            raise ValueError("Demo source checks must not imply human publication approval")
        evidence = urlparse(review["evidenceUrl"])
        if evidence.scheme != "https" or evidence.username or evidence.hostname not in {"www.finlex.fi", "infofinland.fi", "www.suomi.fi"}:
            raise ValueError(f"Unexpected evidence origin: {question_id}")
        en = q.get("translations", {}).get("en")
        if not en or [o["id"] for o in en["options"]] != [o["id"] for o in q["options"]]:
            raise ValueError(f"Missing or misaligned English support: {question_id}")
    finnish = {q["id"]: q for q in questions.values() if q["language"] == "fi"}
    swedish = {q["id"].removesuffix("-sv"): q for q in questions.values() if q["language"] == "sv"}
    if finnish.keys() != swedish.keys():
        raise ValueError("Bilingual demo concepts do not match")
    for key, fi in finnish.items():
        sv = swedish[key]
        if fi["correctOptionId"] != sv["correctOptionId"] or fi["topicId"] != sv["topicId"] or fi["translations"]["en"] != sv["translations"]["en"]:
            raise ValueError(f"Bilingual answer key or English support mismatch: {key}")
    lessons = {(t["id"], language): lesson for t in content["topics"] for language, lesson in t.get("lessons", {}).items()}
    lesson_reviews = {(r["topicId"], r["language"]): r for r in ledger.get("lessonReviews", [])}
    if len(lesson_reviews) != len(ledger.get("lessonReviews", [])) or lessons.keys() != lesson_reviews.keys():
        raise ValueError("Every authored lesson needs exactly one source review")
    for key, lesson in lessons.items():
        review = lesson_reviews[key]
        if lesson["status"] != "DEMO" or review["sha256"] != fingerprint(lesson):
            raise ValueError(f"Lesson changed after source review: {key}")
        if review["publicationApproved"] or review["reviewType"] != "ASSISTANT_SOURCE_CHECK" or date.fromisoformat(review["checkedAt"]) > date.today():
            raise ValueError(f"Invalid lesson review: {key}")
        checks = {s["sectionId"]: s for s in review["sections"]}
        if len(checks) != len(review["sections"]) or set(checks) != {s["id"] for s in lesson["sections"]}:
            raise ValueError(f"Missing or duplicate section review: {key}")
        for section in lesson["sections"]:
            references = checks[section["id"]]["sources"]
            if not references or sorted(s["sourceUrl"] for s in references) != sorted(s["url"] for s in section["sources"]):
                raise ValueError(f"Missing lesson source evidence: {key}")
            for reference in references:
                evidence = urlparse(reference["evidenceUrl"])
                if not reference["claim"] or not reference["locator"] or evidence.scheme != "https" or evidence.username or evidence.hostname not in {"www.finlex.fi", "infofinland.fi", "www.suomi.fi"}:
                    raise ValueError(f"Invalid lesson source evidence: {key}")
    for topic in content["topics"]:
        variants = topic.get("lessons", {})
        if variants and (set(variants) != {"fi", "sv", "en"} or len({(lesson["id"], tuple(s["id"] for s in lesson["sections"])) for lesson in variants.values()}) != 1):
            raise ValueError("Bundled lesson variants must align in FI, SV and EN")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fingerprints", action="store_true", help="Print fingerprints for an editor; does not update or approve the ledger")
    parser.add_argument("--write-coverage", action="store_true", help="Regenerate docs/CONTENT-COVERAGE.md from the objectives layer")
    args = parser.parse_args()
    path = ROOT / "app/src/main/assets/demo-content.json"
    if path.stat().st_size > 2 * 1024 * 1024:
        raise ValueError("Bundled content exceeds the import limit")
    content = read_json(path)
    if args.fingerprints:
        hashes = {q["id"]: fingerprint(q) for q in content["questions"]}
        hashes.update({f"lesson:{t['id']}:{language}": fingerprint(lesson) for t in content["topics"] for language, lesson in t.get("lessons", {}).items()})
        print(json.dumps(hashes, indent=2))
        return
    verify_objectives(content)
    if args.write_coverage:
        COVERAGE_REPORT.write_text(coverage_markdown(content), encoding="utf-8", newline=chr(10))
        print(f"Wrote {COVERAGE_REPORT.relative_to(ROOT)}")
        return
    if content.get("objectives") and (not COVERAGE_REPORT.is_file() or COVERAGE_REPORT.read_text(encoding="utf-8") != coverage_markdown(content)):
        raise ValueError("docs/CONTENT-COVERAGE.md is out of date; run verify-content.py --write-coverage")
    verify(content, read_json(ROOT / "docs/source-review.json"))
    print(f"Content review ledger passed: {len(content['questions'])} DEMO questions, {sum(len(t.get('lessons', {})) for t in content['topics'])} lesson variants, package v{content['version']}; human publication approval remains pending.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError) as error:
        print(f"Content check failed: {error}", file=sys.stderr)
        sys.exit(1)
